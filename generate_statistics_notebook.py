    "    \"\"\"Reproject a LST GeoTIFF onto the 50m analysis grid.\"\"\"\n",
    "    with rasterio.open(tif_path) as src:\n",
    "        dst = np.full((grid['nrows'], grid['ncols']), np.nan, dtype=np.float32)\n",
