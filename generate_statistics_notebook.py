    "def pop_zone_stats(tif_path, layer_name, masks_dict, grid):\n",
    "    arr = resample_to_grid(tif_path, grid, method=Resampling.sum)\n",
    "    if arr is None:\n",
    "        print(f'  {layer_name}: NOT FOUND'); return []\n",
    "    rows = []\n",
    "    for zone, mask in [('Informal', masks_dict['informal']), ('Formal (non-informal)', masks_dict['formal'])]:\n",
    "        v = arr[mask]; v = v[np.isfinite(v)]\n",
    "        total = float(np.nansum(v))\n",
    "        area  = float(np.sum(mask)) * pixel_area_ha\n",
    "        rows.append({'layer': layer_name, 'zone': zone,\n",
    "                     'total_count': total, 'area_ha': area,\n",
    "                     'pop_density_per_ha': total/area if area > 0 else np.nan})\n",
    "        print(f'  {layer_name} | {zone}: {total:,.0f} people  ({total/area:.1f}/ha)')\n",
    "    return rows\n",
    "\n",
    "masks_dict = {'informal': informal_mask, 'formal': formal_mask}\n",
    "pop_rows = []\n",
    "for path, name in [(POP_GENERAL,  'General population'),\n",
    "                    (POP_CHILDREN, 'Children <5'),\n",
    "                    (POP_ELDERLY,  'Elderly 65+')]:\n",
    "    pop_rows += pop_zone_stats(path, name, masks_dict, grid)\n",
    "\n",
    "pop_df = pd.DataFrame(pop_rows)\n",
